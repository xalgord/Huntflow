#!/usr/bin/env node
/**
 * Builds HuntFlow for the npm-published app target (`npm install huntflow`).
 *
 * The hosted website (huntflow.xalgorix.com) and the local app share a single
 * codebase, but they ship as two distinct user experiences. The structural
 * difference between them is large enough that runtime branching alone
 * isn't enough — we want the published npm tarball to *physically not
 * contain* marketing surfaces (landing page, pricing, demo workspace),
 * both for bundle size and so a curious user opening `node_modules/huntflow/build`
 * sees only the app.
 *
 * Strategy:
 *   1. Backup the marketing route source files to a sibling `.build-app-backup`
 *      directory (outside `src/` so SvelteKit/Vite never see the duplicates).
 *   2. Replace `src/routes/+page.svelte` with a tiny stub that redirects to
 *      `/dashboard`, so a visitor hitting `/` lands directly in the app.
 *   3. Delete `src/routes/pricing/` and `src/routes/demo/`.
 *   4. Run `vite build` with `BUILD_TARGET=app` so `IS_APP` / `IS_WEB`
 *      constants resolve correctly and dead-code branches are tree-shaken.
 *   5. Restore everything from backup in a `finally` block — this MUST run
 *      whether the build succeeded, failed, or was killed mid-way, so the
 *      working tree is never left in a half-stripped state.
 *
 * Idempotency:
 *   If a previous run was killed before the restore step, the backup
 *   directory may already exist. We refuse to start in that case and ask
 *   the user to manually run the restore (or delete the backup if they're
 *   sure the working tree is clean) — destroying an unrestored backup
 *   would lose their marketing source files.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const routesDir = join(root, 'src', 'routes');
const backupDir = join(root, '.build-app-backup');

// Marketing surfaces stripped from the app build. Each entry is a path
// relative to the repo root.
const MARKETING_PATHS = [
  'src/routes/+page.svelte',
  'src/routes/pricing',
  'src/routes/demo'
];

// Stub landing page that replaces the marketing `+page.svelte` for the
// app build. Anyone hitting `/` is sent to the dashboard immediately —
// the app has no marketing surface.
//
// We use `goto(..., { replaceState: true })` so the redirect doesn't
// add a junk entry to history. The fallback `<meta http-equiv="refresh">`
// covers the (rare) case where JS is disabled or hasn't booted yet.
const APP_LANDING_STUB = `<script lang="ts">
  // Auto-generated by bin/build-app.mjs for the npm-published app build.
  // The marketing landing page is stripped at build time; this stub
  // redirects every visitor to the dashboard so the app has no
  // marketing surface at all.
  import { browser } from '$app/environment';
  import { goto } from '$app/navigation';
  import { onMount } from 'svelte';

  onMount(() => {
    if (browser) void goto('/dashboard', { replaceState: true });
  });
</script>

<svelte:head>
  <title>HuntFlow</title>
  <meta name="robots" content="noindex" />
  <meta http-equiv="refresh" content="0; url=/dashboard" />
</svelte:head>

<main class="flex min-h-screen items-center justify-center bg-slate-950 px-4 text-slate-300">
  <p class="text-sm" aria-live="polite">Opening HuntFlow&hellip;</p>
</main>
`;

function log(message) {
  console.log(`[build-app] ${message}`);
}

function backupExists() {
  return existsSync(backupDir);
}

function moveIntoBackup(relativePath) {
  const source = join(root, relativePath);
  if (!existsSync(source)) return;
  const dest = join(backupDir, relativePath);
  mkdirSync(dirname(dest), { recursive: true });
  renameSync(source, dest);
}

function restoreFromBackup() {
  if (!backupExists()) return;
  const walk = (dir, base) => {
    for (const entry of readdirSync(dir)) {
      const abs = join(dir, entry);
      const rel = base ? join(base, entry) : entry;
      const stats = statSync(abs);
      if (stats.isDirectory()) {
        walk(abs, rel);
      } else {
        const dest = join(root, rel);
        // Remove whatever is at the destination first (e.g. the stub
        // `+page.svelte` we wrote earlier in this run) so the rename
        // doesn't fail with EEXIST.
        if (existsSync(dest)) rmSync(dest, { recursive: true, force: true });
        mkdirSync(dirname(dest), { recursive: true });
        renameSync(abs, dest);
      }
    }
  };
  walk(backupDir, '');
  rmSync(backupDir, { recursive: true, force: true });
}

if (backupExists()) {
  console.error(
    `[build-app] Aborting: ${backupDir} already exists. A previous build was interrupted before restoring marketing routes.\n` +
      `Manually move its contents back into src/routes/ (or delete the backup if the working tree is already clean), then re-run.`
  );
  process.exit(1);
}

if (!existsSync(routesDir)) {
  console.error(`[build-app] Aborting: ${routesDir} not found.`);
  process.exit(1);
}

let buildExitCode = 1;

try {
  log('Stripping marketing surfaces from src/routes/ ...');
  mkdirSync(backupDir, { recursive: true });
  for (const path of MARKETING_PATHS) {
    moveIntoBackup(path);
  }

  log('Writing app landing stub at src/routes/+page.svelte ...');
  writeFileSync(join(routesDir, '+page.svelte'), APP_LANDING_STUB, 'utf8');

  log('Running vite build with BUILD_TARGET=app ...');
  const result = spawnSync('npm', ['run', 'build'], {
    cwd: root,
    stdio: 'inherit',
    shell: process.platform === 'win32',
    env: { ...process.env, BUILD_TARGET: 'app' }
  });

  buildExitCode = result.status ?? 1;
  if (buildExitCode === 0) {
    log('Build succeeded.');
  } else {
    log(`Build exited with code ${buildExitCode}.`);
  }
} finally {
  // ALWAYS restore, even if the build crashed or this process is being
  // killed. Leaving the working tree half-stripped would corrupt the
  // user's source.
  log('Restoring marketing routes from backup ...');
  try {
    // Remove the stub `+page.svelte` we wrote so the original (in backup)
    // can be restored cleanly.
    const stub = join(routesDir, '+page.svelte');
    if (existsSync(stub)) rmSync(stub, { force: true });
    restoreFromBackup();
    log('Restore complete.');
  } catch (err) {
    console.error('[build-app] Restore failed:', err);
    console.error(
      `[build-app] Manually move contents of ${backupDir} back into src/routes/ before continuing.`
    );
    // Force a non-zero exit so CI fails loudly rather than silently
    // shipping a corrupted working tree.
    process.exit(1);
  }
}

process.exit(buildExitCode);
